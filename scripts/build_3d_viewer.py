#!/usr/bin/env python3
"""Build the classic browser bundle for HTTP and file:// viewing.

Requires Node.js and npm. The first build downloads pinned esbuild through npm;
subsequent builds can use --offline. No GLB or assembly data is embedded.
"""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ESBUILD_VERSION = '0.25.10'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='Fail if the committed bundle differs; do not replace it')
    parser.add_argument('--offline', action='store_true',
                        help='Use cached npm packages without accessing the registry')
    parser.add_argument('--output', type=Path, default=ROOT / 'docs/3d/viewer.bundle.js')
    args = parser.parse_args()
    npm = shutil.which('npm')
    if not npm:
        parser.error('Install Node.js and npm to rebuild the viewer bundle')
    command = [npm, 'exec', '--yes', f'--package=esbuild@{ESBUILD_VERSION}']
    if args.offline:
        command.append('--offline')
    command.extend(['--', 'esbuild'])
    version = subprocess.check_output([*command, '--version'], cwd=ROOT, text=True).strip()
    if version != ESBUILD_VERSION:
        raise SystemExit(f'Expected esbuild {ESBUILD_VERSION}, found {version}')
    with tempfile.TemporaryDirectory(prefix='ulva-viewer-') as temporary:
        target = Path(temporary) / 'viewer.bundle.js'
        metadata = Path(temporary) / 'metafile.json'
        subprocess.run([
            *command, 'docs/3d/viewer.js', '--bundle', '--minify', '--format=iife',
            '--platform=browser', '--target=es2020', '--charset=utf8',
            '--legal-comments=inline', f'--outfile={target}', f'--metafile={metadata}',
            '--banner:js=/* Generated by scripts/build_3d_viewer.py; edit viewer.js. Three.js: MIT, see vendor/LICENSE.txt. */',
        ], cwd=ROOT, check=True)
        report = json.loads(metadata.read_text())
        inputs = set(report['inputs'])
        if any(name.endswith(('VRMLLoader.js', 'GLTFExporter.js')) for name in inputs):
            raise SystemExit('Export-only modules unexpectedly entered the browser bundle')
        if any(output.get('imports') for output in report['outputs'].values()):
            raise SystemExit('The browser bundle contains external JavaScript dependencies')
        data = target.read_bytes()
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != data:
                raise SystemExit('Viewer bundle is stale. Run python3 scripts/build_3d_viewer.py')
            print(f'Viewer bundle is current ({len(data):,} bytes).')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(data)
            print(f'Built {args.output} ({len(data):,} bytes; {len(inputs)} source modules).')


if __name__ == '__main__':
    main()
